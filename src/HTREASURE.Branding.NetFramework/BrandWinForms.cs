    /// <summary>HTREASURE branding helpers for Windows Forms (.NET Framework port of BrandWinForms).</summary>
    public static class BrandWinForms
    {
        public static readonly Color DeepNavy = ToColor(BrandColors.DeepNavy);
        public static readonly Color TechnologyBlue = ToColor(BrandColors.TechnologyBlue);
        public static readonly Color ElectricBlue = ToColor(BrandColors.ElectricBlue);
        public static readonly Color SilverGrey = ToColor(BrandColors.SilverGrey);
        public static readonly Color Edge = ToColor(BrandColors.Edge);
        public static readonly Color PageGrey = ToColor(BrandColors.PageGrey);
        public static readonly Color LineGrey = ToColor(BrandColors.LineGrey);
        public static readonly Color MutedText = ToColor(BrandColors.MutedText);

        private static readonly Lazy<Icon> LazyProductIcon = new Lazy<Icon>(() =>
        {
            using (var stream = BrandAssets.Open(BrandAssets.CorporateIcon)) return new Icon(stream);
        });

        private static readonly Lazy<Image> LazyProductImage = new Lazy<Image>(() => LoadImage(BrandAssets.Open(BrandAssets.CorporateIconPng)));

        public static Color ToColor(string colour)
        {
            byte a, r, g, b;
            BrandColors.Parse(colour, out a, out r, out g, out b);
            return Color.FromArgb(a, r, g, b);
        }

        /// <summary>The product's multi-size icon (the corporate icon until a product icon is generated by the kit).</summary>
        public static Icon ProductIcon { get { return LazyProductIcon.Value; } }

        /// <summary>The product icon as a 256 px image, for About boxes and headers.</summary>
        public static Image ProductImage { get { return LazyProductImage.Value; } }

        public static void ApplyIcon(Form form) { form.Icon = ProductIcon; }

        public static Image GetLogo(LogoVariant variant, int pixelWidth)
        {
            return LoadImage(BrandAssets.Open(BrandAssets.LogoPath(variant, pixelWidth)));
        }

        /// <summary>A status strip with the discreet company attribution on the right.</summary>
        public static StatusStrip CreateFooter(string leftText)
        {
            var strip = new StatusStrip { SizingGrip = false, BackColor = PageGrey, ForeColor = MutedText };
            strip.Items.Add(new ToolStripStatusLabel(leftText ?? "Ready") { Spring = true, TextAlign = ContentAlignment.MiddleLeft });
            strip.Items.Add(new ToolStripStatusLabel(BrandInfo.ShortCopyright + " · " + BrandInfo.Attribution));
            return strip;
        }

        /// <summary>Draws an image into a rectangle with high-quality resampling, keeping its aspect ratio.</summary>
        public static void DrawImageFit(Graphics g, Image image, Rectangle bounds, ContentAlignment align)
        {
            if (bounds.Width <= 0 || bounds.Height <= 0) return;
            float scale = Math.Min((float)bounds.Width / image.Width, (float)bounds.Height / image.Height);
            var size = new SizeF(image.Width * scale, image.Height * scale);
            float x;
            if (align == ContentAlignment.TopLeft || align == ContentAlignment.MiddleLeft || align == ContentAlignment.BottomLeft) x = bounds.X;
            else if (align == ContentAlignment.TopRight || align == ContentAlignment.MiddleRight || align == ContentAlignment.BottomRight) x = bounds.Right - size.Width;
            else x = bounds.X + (bounds.Width - size.Width) / 2;
            float y = bounds.Y + (bounds.Height - size.Height) / 2;
            g.InterpolationMode = InterpolationMode.HighQualityBicubic;
            g.PixelOffsetMode = PixelOffsetMode.HighQuality;
            g.DrawImage(image, x, y, size.Width, size.Height);
        }

        internal static Image LoadImage(Stream stream)
        {
            using (stream)
            using (var decoded = Image.FromStream(stream))
                return new Bitmap(decoded);
        }
    }

    /// <summary>The Inter brand typeface (loaded privately from the embedded file) and the Segoe UI application font.
    /// Fonts from a private collection must be drawn with GDI+ (Graphics.DrawString, or labels with
    /// UseCompatibleTextRendering), not TextRenderer.</summary>
    public static class BrandFonts
    {
        private static readonly List<PrivateFontCollection> Collections = new List<PrivateFontCollection>();
        private static readonly Lazy<FontFamily> Regular = new Lazy<FontFamily>(() => Load(BrandAssets.InterRegular));
        private static readonly Lazy<FontFamily> SemiBold = new Lazy<FontFamily>(() => Load(BrandAssets.InterSemiBold));

        public const string ApplicationFontName = "Segoe UI";

        /// <summary>Inter at <paramref name="pixelSize"/> pixels; Segoe UI if Inter cannot be loaded.</summary>
        public static Font Brand(float pixelSize, bool semiBold)
        {
            var family = semiBold ? SemiBold.Value : Regular.Value;
            if (family != null) return new Font(family, pixelSize, FontStyle.Regular, GraphicsUnit.Pixel);
            return new Font(ApplicationFontName, pixelSize, semiBold ? FontStyle.Bold : FontStyle.Regular, GraphicsUnit.Pixel);
        }

        /// <summary>Inter in points (for labels that scale with the form's DPI).</summary>
        public static Font BrandPoints(float pointSize, bool semiBold)
        {
            var family = semiBold ? SemiBold.Value : Regular.Value;
            if (family != null) return new Font(family, pointSize, FontStyle.Regular, GraphicsUnit.Point);
            return new Font(ApplicationFontName, pointSize, semiBold ? FontStyle.Bold : FontStyle.Regular, GraphicsUnit.Point);
        }

        public static Font Application(float pointSize = 9f, FontStyle style = FontStyle.Regular)
        {
            return new Font(ApplicationFontName, pointSize, style);
        }

        private static FontFamily Load(string asset)
        {
            try
            {
                byte[] data = BrandAssets.ReadAllBytes(asset);
                IntPtr memory = Marshal.AllocCoTaskMem(data.Length); // must stay allocated while the font is in use
                Marshal.Copy(data, 0, memory, data.Length);
                var collection = new PrivateFontCollection();
                collection.AddMemoryFont(memory, data.Length);
                Collections.Add(collection);
                var family = collection.Families[0];
                return family.IsStyleAvailable(FontStyle.Regular) ? family : null;
            }
            catch (Exception ex) when (ex is IOException || ex is ExternalException || ex is ArgumentException)
            {
                return null;
            }
        }
    }

    /// <summary>Shows an image with high-quality resampling at the control's size, so logos stay sharp at every scale.</summary>
    public class BrandImageBox : Control
    {
        private Image image;

        public BrandImageBox()
        {
            SetStyle(ControlStyles.AllPaintingInWmPaint | ControlStyles.OptimizedDoubleBuffer | ControlStyles.ResizeRedraw
                | ControlStyles.SupportsTransparentBackColor | ControlStyles.UserPaint, true);
            BackColor = Color.Transparent;
            ImageAlign = ContentAlignment.MiddleCenter;
            TabStop = false;
        }

        [DefaultValue(null)]
        public Image Image
        {
            get { return image; }
            set { image = value; Invalidate(); }
        }

        [DefaultValue(ContentAlignment.MiddleCenter)]
        public ContentAlignment ImageAlign { get; set; }

        protected override void OnPaint(PaintEventArgs e)
        {
            base.OnPaint(e);
            if (image != null) BrandWinForms.DrawImageFit(e.Graphics, image, ClientRectangle, ImageAlign);
        }
    }

    /// <summary>HTREASURE splash screen: corporate background, product name, version, progress bar and copyright,
    /// laid out from brand.json and drawn at the monitor's DPI.</summary>
    public class BrandSplashForm : Form
    {
        public static readonly Size LogicalSize = new Size(640, 360);

        private readonly string product;
        private readonly string version;
        private double progress;
        private string status;
        private Image background;

        public BrandSplashForm(string productName = null, string version = null)
        {
            product = productName ?? BrandInfo.ProductName;
            this.version = version ?? BrandInfo.ProductVersion;
            Text = product;
            FormBorderStyle = FormBorderStyle.None;
            StartPosition = FormStartPosition.CenterScreen;
            ShowInTaskbar = true;
            BackColor = BrandWinForms.DeepNavy;
            AutoScaleMode = AutoScaleMode.None;
            DoubleBuffered = true;
            Icon = BrandWinForms.ProductIcon;
            float scale = DeviceDpiScale();
            ClientSize = new Size((int)(LogicalSize.Width * scale), (int)(LogicalSize.Height * scale));
        }

        private float DeviceDpiScale()
        {
            using (var g = CreateGraphics()) return g.DpiX / 96f;
        }

        /// <summary>Updates the progress bar (0..1) and optional status text, and repaints immediately.</summary>
        public void Report(double fraction, string statusText = null)
        {
            progress = Math.Max(0, Math.Min(1, fraction));
            status = statusText;
            Invalidate();
            Update();
        }

        protected override void OnPaint(PaintEventArgs e)
        {
            var g = e.Graphics;
            if (background == null)
                background = BrandWinForms.LoadImage(BrandAssets.Open(ClientSize.Width > 1280
                    ? "SplashScreens/HTREASURE-splash-base-1920x1080.png"
                    : "SplashScreens/HTREASURE-splash-base-1280x720.png"));
            g.InterpolationMode = InterpolationMode.HighQualityBicubic;
            g.PixelOffsetMode = PixelOffsetMode.HighQuality;
            g.DrawImage(background, ClientRectangle);

            var cfg = BrandInfo.Config;
            float s = ClientSize.Width / (float)cfg.SplashDesignSize[0];
            g.SmoothingMode = SmoothingMode.AntiAlias;
            g.TextRenderingHint = TextRenderingHint.AntiAliasGridFit;

            DrawText(g, product, cfg.ProductName, s, null);
            DrawText(g, (cfg.Version.Format ?? "Version {version}").Replace("{version}", version), cfg.Version, s, null);

            var bar = cfg.ProgressBar;
            var track = new RectangleF(bar.X * s, bar.Y * s, bar.Width * s, Math.Max(2, bar.Height * s));
            using (var trackBrush = new SolidBrush(BrandWinForms.ToColor(bar.Track))) g.FillRectangle(trackBrush, track);
            using (var fillBrush = new SolidBrush(BrandWinForms.ToColor(bar.Fill)))
                g.FillRectangle(fillBrush, track.X, track.Y, (float)(track.Width * progress), track.Height);

            if (!string.IsNullOrEmpty(status))
            {
                var slot = new BrandConfig.SplashText { X = cfg.Footer.X, Y = cfg.Version.Y, Size = cfg.Footer.Size, Weight = cfg.Footer.Weight, Color = cfg.Footer.Color };
                DrawText(g, status, slot, s, track.Right);
            }
            DrawText(g, BrandInfo.Copyright, cfg.Footer, s, null);
            DrawText(g, "Publisher: " + BrandInfo.Publisher, cfg.Footer, s, track.Right);
        }

        protected override void Dispose(bool disposing)
        {
            if (disposing && background != null) background.Dispose();
            base.Dispose(disposing);
        }

        private static void DrawText(Graphics g, string text, BrandConfig.SplashText slot, float scale, float? rightEdge)
        {
            using (var font = BrandFonts.Brand(slot.Size * scale, slot.Weight == "SemiBold"))
            using (var brush = new SolidBrush(BrandWinForms.ToColor(slot.Color)))
            {
                var family = font.FontFamily;
                float ascent = font.Size * family.GetCellAscent(font.Style) / family.GetEmHeight(font.Style);
                var format = StringFormat.GenericTypographic;
                float x = rightEdge.HasValue ? rightEdge.Value - g.MeasureString(text, font, PointF.Empty, format).Width : slot.X * scale;
                g.DrawString(text, font, brush, x, slot.Y * scale - ascent, format);
            }
        }
    }

    /// <summary>Standard HTREASURE About box: product icon, name, version, description, copyright, publisher and
    /// company details, with the corporate logo.</summary>
    public class BrandAboutForm : Form
    {
        private readonly FlowLayoutPanel details;

        public BrandAboutForm(string productName = null, string version = null, string description = null)
        {
            string product = productName ?? BrandInfo.ProductName;
            description = description ?? BrandInfo.ProductDescription;

            Text = "About " + product;
            Font = BrandFonts.Application();
            AutoScaleMode = AutoScaleMode.Dpi;
            AutoScaleDimensions = new SizeF(96F, 96F);
            FormBorderStyle = FormBorderStyle.FixedDialog;
            MaximizeBox = MinimizeBox = false;
            ShowInTaskbar = false;
            StartPosition = FormStartPosition.CenterParent;
            BackColor = Color.White;
            AutoSize = true;
            AutoSizeMode = AutoSizeMode.GrowAndShrink;
            Icon = BrandWinForms.ProductIcon;

            details = new FlowLayoutPanel
            {
                FlowDirection = FlowDirection.TopDown, AutoSize = true, WrapContents = false,
                Margin = new Padding(0), MaximumSize = new Size(400, 0),
            };
            details.Controls.Add(MakeLabel(product, new Font(BrandFonts.ApplicationFontName, 15f, FontStyle.Bold), BrandWinForms.DeepNavy, 0));
            details.Controls.Add(MakeLabel("Version " + (version ?? BrandInfo.ProductVersion), null, BrandWinForms.MutedText, 0));
            if (!string.IsNullOrWhiteSpace(description))
                details.Controls.Add(MakeLabel(description, null, BrandWinForms.DeepNavy, 10));
            details.Controls.Add(MakeLabel(BrandInfo.Copyright, null, BrandWinForms.DeepNavy, 14));
            details.Controls.Add(MakeLabel("Publisher: " + BrandInfo.Publisher, null, BrandWinForms.MutedText, 14));
            details.Controls.Add(MakeLabel(BrandInfo.RegistrationLine, null, BrandWinForms.MutedText, 0));
            details.Controls.Add(MakeLabel(BrandInfo.RegisteredAddress, null, BrandWinForms.MutedText, 0));

            var icon = new BrandImageBox { Image = BrandWinForms.ProductImage, Size = new Size(64, 64), Margin = new Padding(0, 4, 20, 0) };
            var logo = new BrandImageBox
            {
                Image = BrandWinForms.GetLogo(LogoVariant.HorizontalColor, 1024), ImageAlign = ContentAlignment.MiddleLeft,
                Size = new Size(200, 41), Anchor = AnchorStyles.Left, Margin = new Padding(0),
            };
            var ok = new Button
            {
                Text = "OK", DialogResult = DialogResult.OK, AutoSize = true, MinimumSize = new Size(88, 30),
                Anchor = AnchorStyles.Right, FlatStyle = FlatStyle.Flat, BackColor = BrandWinForms.TechnologyBlue,
                ForeColor = Color.White, Margin = new Padding(24, 0, 0, 0), UseVisualStyleBackColor = false,
            };
            ok.FlatAppearance.BorderSize = 0;

            ButtonPanel = new FlowLayoutPanel { AutoSize = true, FlowDirection = FlowDirection.LeftToRight, WrapContents = false, Margin = new Padding(24, 0, 0, 0), Anchor = AnchorStyles.Right };
            ButtonPanel.Controls.Add(ok);

            var bottom = new TableLayoutPanel
            {
                ColumnCount = 2, RowCount = 1, AutoSize = true, Dock = DockStyle.Fill,
                Margin = new Padding(0, 22, 0, 0), Padding = new Padding(0, 16, 0, 0),
            };
            bottom.ColumnStyles.Add(new ColumnStyle(SizeType.Percent, 100));
            bottom.ColumnStyles.Add(new ColumnStyle(SizeType.AutoSize));
            bottom.Controls.Add(logo, 0, 0);
            bottom.Controls.Add(ButtonPanel, 1, 0);
            bottom.Paint += (s, e) =>
            {
                using (var pen = new Pen(BrandWinForms.LineGrey)) e.Graphics.DrawLine(pen, 0, 0, bottom.Width, 0);
            };

            var root = new TableLayoutPanel
            {
                ColumnCount = 2, RowCount = 2, AutoSize = true, AutoSizeMode = AutoSizeMode.GrowAndShrink,
                Padding = new Padding(24, 24, 24, 20), Dock = DockStyle.Fill,
            };
            root.Controls.Add(icon, 0, 0);
            root.Controls.Add(details, 1, 0);
            root.Controls.Add(bottom, 0, 1);
            root.SetColumnSpan(bottom, 2);
            Controls.Add(root);
            AcceptButton = ok;
            CancelButton = ok;
        }

        /// <summary>Button area next to OK, for application-specific actions (inserted to the left of OK).</summary>
        protected FlowLayoutPanel ButtonPanel { get; private set; }

        /// <summary>Adds an extra line under the company details (for example the build and runtime).</summary>
        public void AddDetail(string text)
        {
            details.Controls.Add(MakeLabel(text, null, BrandWinForms.MutedText, 10));
        }

        /// <summary>Adds a link-style button to the left of OK.</summary>
        public LinkLabel AddLink(string text, EventHandler onClick)
        {
            var link = new LinkLabel { Text = text, AutoSize = true, Margin = new Padding(0, 8, 16, 0), LinkColor = BrandWinForms.TechnologyBlue };
            link.LinkClicked += (s, e) => onClick(s, e);
            ButtonPanel.Controls.Add(link);
            ButtonPanel.Controls.SetChildIndex(link, 0);
            return link;
        }

        private static Label MakeLabel(string text, Font font, Color colour, int top)
        {
            var label = new Label { Text = text, AutoSize = true, ForeColor = colour, Margin = new Padding(0, top, 0, 2), MaximumSize = new Size(400, 0), UseMnemonic = false };
            if (font != null) label.Font = font;
            return label;
        }
    }
